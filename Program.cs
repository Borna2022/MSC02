using Serilog;
// این خط یک کتابخانه را وارد می‌کند که به ما اجازه می‌دهد با پایگاه داده کار کنیم
// (ای‌اف کور یکی از ابزارهای معروف برای ارتباط با پایگاه داده است)
using Microsoft.EntityFrameworkCore;

// این خط فضای نامی را وارد می‌کند که کلاس پایگاه داده برنامه ما در آن قرار دارد
// (AppDbContext در این فضا قرار دارد)
using MSC02.Data;

// این خط فضای نامی را وارد می‌کند که سرویس‌های برنامه ما در آن قرار دارند
// (کلاس GatewayListener در این فضا قرار دارد)
using MSC02.Services;


Log.Logger = new LoggerConfiguration()

    // ثبت لاگ‌ها در ترمینال
    .WriteTo.Console()

    // ثبت لاگ‌ها در فایل روزانه
    .WriteTo.File(
        "logs/telegram-.log",
        rollingInterval: RollingInterval.Day)

    .CreateLogger();

// این خط یک شیء سازنده از کلاس WebApplication می‌سازد
// این شیء مسئول راه‌اندازی و پیکربندی کل برنامه وب ما است
// متغیر args آرگومان‌های خط فرمان هستند که وقتی برنامه را اجرا می‌کنیم به آن پاس می‌شوند
var builder = WebApplication.CreateBuilder(args);


// ------------------- بخش اضافه کردن سرویس‌ها -------------------
builder.Services.AddSerilog();
// این خط کنترلرها را به همراه ویوها (نمایش‌ها) به برنامه اضافه می‌کند
// متد AddRazorRuntimeCompilation باعث می‌شود وقتی فایل‌های ویو را تغییر می‌دهیم
// بدون نیاز به توقف و اجرای مجدد برنامه، تغییرات اعمال شوند (مخصوص زمان توسعه)
builder.Services.AddControllersWithViews().AddRazorRuntimeCompilation();

// این خط پایگاه داده برنامه را به سیستم تزریق وابستگی معرفی می‌کند
// (تزریق وابستگی یعنی به جای ساختن دستی اشیاء، خود فریم‌ورک آن‌ها را می‌سازد و به ما می‌دهد)
builder.Services.AddDbContext<AppDbContext>(options =>
{
    // این خط به برنامه می‌گوید که از پایگاه داده پستگرس استفاده کند
    // و رشته اتصال (Connection String) را از فایل تنظیمات با نام DefaultConnection می‌خواند
    // رشته اتصال یعنی اطلاعاتی مثل آدرس سرور، نام پایگاه داده، نام کاربری و رمز عبور
    options.UseNpgsql(builder.Configuration.GetConnectionString("DefaultConnection"));
});

// این خط برنامه وب را با تمام تنظیماتی که تا حالا انجام دادیم می‌سازد
// از این لحظه به بعد، دیگر نمی‌توانیم سرویس جدیدی اضافه کنیم
var app = builder.Build();

// ------------------- بخش پیکربندی خط لوله درخواست‌ها -------------------

// این شرط بررسی می‌کند که آیا برنامه در حالت توسعه (Development) اجرا می‌شود یا خیر
// علامت ! یعنی اگر در حالت توسعه نبود (یعنی در حالت انتشار یا Production بود)
if (!app.Environment.IsDevelopment())
{
    // این خط یک میان‌افزار (Middleware) اضافه می‌کند که خطاها را مدیریت می‌کند
    // اگر خطایی رخ دهد، کاربر را به مسیر Home/Error هدایت می‌کند
    app.UseExceptionHandler("/Home/Error");

    // این خط هدر امنیتی اچ‌اس‌تی‌اس را فعال می‌کند
    // این هدر به مرورگر می‌گوید که همیشه از پروتکل امن (اچ‌تی‌تی‌پی‌اس) استفاده کند
    // مقدار پیش‌فرض آن ۳۰ روز است؛ می‌توانید برای محیط واقعی آن را تغییر دهید
    // آدرس زیر برای اطلاعات بیشتر: https://aka.ms/aspnetcore-hsts
    app.UseHsts();
}

// این خط باعث می‌شود اگر کاربری با پروتکل غیرامن (اچ‌تی‌تی‌پی) وارد شد
// به صورت خودکار به پروتکل امن (اچ‌تی‌تی‌پی‌اس) هدایت شود
app.UseHttpsRedirection();

// این خط به برنامه اجازه می‌دهد فایل‌های ثابت مثل تصویر، سی‌اس‌اس و جاوااسکریپت را ارائه دهد
// این فایل‌ها در پوشه wwwroot قرار دارند
app.UseStaticFiles();

// این خط سیستم مسیریابی را فعال می‌کند
// مسیریابی یعنی تشخیص این که کدام آدرس اینترنتی باید به کدام کنترلر و اکشن برود
app.UseRouting();

// این خط سیستم احراز هویت (Authorization) را فعال می‌کند
// یعنی بررسی می‌کند که آیا کاربر اجازه دسترسی به یک صفحه را دارد یا خیر
app.UseAuthorization();

// این خط به برنامه می‌گوید که کنترلرهای مبتنی بر ویژگی (Attribute Routing) را نقشه‌برداری کند
// یعنی کنترلرهایی که با [Route] یا [HttpGet] و امثال آن مسیرشان مشخص شده است
app.MapControllers();

// این خط یک الگوی مسیریابی پیش‌فرض تعریف می‌کند
// یعنی وقتی کاربر آدرسی وارد نکرد، به طور خودکار به کنترلر هوم و اکشن ایندکس می‌رود
// علامت سؤال در {id?} یعنی این پارامتر اختیاری است و می‌تواند نباشد
app.MapControllerRoute(
    name: "default",
    pattern: "{controller=Home}/{action=Index}/{id?}");

// این خط یک نمونه (شیء) از کلاس گیت وی لیستنر می‌سازد
// این کلاس احتمالاً یک شنونده (لیستنر) است که به یک درگاه (گیت وی) متصل می‌شود
// (مثلاً یک درگاه پرداخت یا یک سرویس پیام‌رسان)
GatewayListener gatewayListener = new GatewayListener();

// این خط متد استارت آسینک را روی شیء ساخته شده فراخوانی می‌کند
// این متد یک وظیفه (تسک) برمی‌گرداند که به صورت ناهمگام (آسینک) اجرا می‌شود
// علامت _ یعنی ما به نتیجه این وظیفه کاری نداریم و آن را نادیده می‌گیریم
// این کار باعث می‌شود برنامه اصلی ما متوقف نشود و به کار خود ادامه دهد
_ = gatewayListener.StartAsync();

// این خط برنامه وب را اجرا می‌کند
// از این لحظه، برنامه شروع به گوش دادن به درخواست‌های ورودی می‌کند
// و تا زمانی که متوقف نشود، به کار خود ادامه می‌دهد
app.Run();